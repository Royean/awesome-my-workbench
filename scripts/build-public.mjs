import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import zlib from 'node:zlib';

const styles = ['style.css', 'minimal.css', 'daily.css', 'mobile.css', 'account.css', 'cgm.css', 'assets.css', 'travel-map.css', 'travel.css', 'originals.css', 'reading.css', 'studio.css', 'studio-library.css', 'studio-health.css', 'studio-domains.css', 'studio-mobile.css', 'layout.css', 'component-card.css', 'components.css', 'finance-overview.css', 'capture.css', 'developer-hub.css', 'hub-components.css', 'hub-development.css', 'hub-teams.css', 'hub-execution.css'];
const sha256 = content => createHash('sha256').update(content).digest('hex');

// Deliberately small: this app uses local named imports and named declarations.
// Fail closed for unsupported module syntax rather than producing a partial bundle.
export async function buildPublic(publicDir = path.resolve(import.meta.dirname, '../public')) {
  publicDir = path.resolve(publicDir);
  const modules = new Map(), visiting = new Set(), chunks = [];
  async function compile(name, entry = false) {
    if (visiting.has(name)) throw Error(`Circular module dependency: ${name}`);
    if (modules.has(name)) return modules.get(name);
    if (!/^[\w-]+\.js$/.test(name)) throw Error(`Unsupported module path: ${name}`);
    visiting.add(name);
    let source = await fs.readFile(path.join(publicDir, name), 'utf8');
    const imports = [];
    source = source.replace(/^import\s*\{([^}]+)\}\s*from\s*['"]\.\/([\w-]+\.js)['"];?\s*$/gm, (_, names, dependency) => {
      const bindings = names.split(',').map(value => value.trim()).filter(Boolean).map(value => {
        const match = /^([\w$]+)(?:\s+as\s+([\w$]+))?$/.exec(value);
        if (!match) throw Error(`Unsupported import in ${name}: ${value}`);
        return match[2] ? `${match[1]}: ${match[2]}` : match[1];
      });
      imports.push({ dependency, bindings });
      return '';
    });
    const bindings = [];
    for (const imported of imports) {
      const namespace = await compile(imported.dependency);
      bindings.push(`const { ${imported.bindings.join(', ')} } = ${namespace};`);
    }
    const exports = [];
    source = source.replace(/^export\s+((?:async\s+)?function\s+|(?:const|let|var|class)\s+)([\w$]+)/gm, (_, declaration, name) => {
      exports.push(name);
      return declaration + name;
    });
    if (/^\s*(?:import\s|export\s)/m.test(source)) throw Error(`Unsupported module syntax in ${name}`);
    const namespace = `__workbenchModule${modules.size}`;
    modules.set(name, namespace);
    visiting.delete(name);
    const body = `// ${name}\n${bindings.join('\n')}\n${source.trim()}\n`;
    chunks.push(entry ? body : `const ${namespace} = (() => {\n${body}return { ${exports.join(', ')} };\n})();\n`);
    return namespace;
  }
  await compile('app.js', true);
  const javascript = `// Generated by scripts/build-public.mjs. Edit the source modules.\n${chunks.join('\n')}`;
  const check = spawnSync(process.execPath, ['--check', '--input-type=module'], { input: javascript, encoding: 'utf8' });
  if (check.status !== 0) throw Error(`Bundle syntax check failed: ${check.stderr || check.error}`);
  const css = (await Promise.all(styles.map(async name => `/* ${name} */\n${(await fs.readFile(path.join(publicDir, name), 'utf8')).trim()}\n`))).join('\n');
  const jsPath = `/assets/app.${sha256(javascript)}.js`, cssPath = `/assets/app.${sha256(css)}.css`;
  let html = await fs.readFile(path.join(publicDir, 'index.html'), 'utf8');
  // A data URI avoids the browser re-requesting favicon.svg on hash navigation.
  // Read from the source each build, so icon edits do not leave stale HTML.
  try {
    const favicon = await fs.readFile(path.join(publicDir, 'favicon.svg'), 'utf8');
    const iconURL = `data:image/svg+xml,${encodeURIComponent(favicon).replace(/'/g, '%27')}`;
    html = html.replace(/<link\b(?=[^>]*\brel="icon")[^>]*>/, tag => tag.replace(/\bhref="[^"]*"/, `href="${iconURL}"`));
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }

  const cssTag = `<link rel="stylesheet" href="${cssPath}" data-workbench-bundle="css">`;
  const jsTag = `<script type="module" src="${jsPath}" data-workbench-bundle="js"></script>`;
  if (html.includes('data-workbench-bundle="css"')) {
    html = html.replace(/<link\b[^>]*data-workbench-bundle="css"[^>]*>/, cssTag);
  } else {
    let count = 0;
    html = html.replace(/<link rel="stylesheet" href="\/(style|minimal|daily|mobile|account|cgm|assets|travel-map|travel|originals|reading|studio|studio-library|studio-health|studio-domains|studio-mobile|layout|component-card|components|finance-overview|capture|developer-hub|hub-components|hub-development|hub-teams|hub-execution)\.css">/g, () => count++ === 0 ? cssTag : '');
    if (count !== styles.length) throw Error(`Expected ${styles.length} source stylesheet links in index.html`);
  }
  if (html.includes('data-workbench-bundle="js"')) {
    html = html.replace(/<script\b[^>]*data-workbench-bundle="js"[^>]*><\/script>/, jsTag);
  } else {
    if (!html.includes('<script type="module" src="/app.js"></script>')) throw Error('Missing app.js entry in index.html');
    html = html.replace('<script type="module" src="/app.js"></script>', jsTag);
  }
  await fs.mkdir(path.join(publicDir, 'assets'), { recursive: true });
  // Retention: keep the current bundle, everything the on-disk index.html referenced before this build,
  // and everything the index.html of the last few commits that changed it references, so open tabs and the previous
  // release never 404. If git is unavailable (e.g. an extracted release without .git), delete nothing.
  const refs = text => (text.match(/\/assets\/app\.[a-f0-9]{64}\.(?:js|css)/g) || []).map(p => path.basename(p));
  let previousIndex = '';
  try { previousIndex = await fs.readFile(path.join(publicDir, 'index.html'), 'utf8'); } catch {}
  const committedIndex = committedFile(publicDir, 'index.html');
  const keep = committedIndex === null ? null : new Set([path.basename(jsPath), path.basename(cssPath), ...refs(previousIndex), ...refs(committedIndex)]);
  await fs.writeFile(path.join(publicDir, jsPath.slice(1)), javascript);
  await fs.writeFile(path.join(publicDir, cssPath.slice(1)), css);
  // Pre-compressed siblings served by server.mjs; deterministic for identical input.
  for (const [asset, content] of [[jsPath, javascript], [cssPath, css]]) {
    const file = path.join(publicDir, asset.slice(1)), bytes = Buffer.from(content);
    await fs.writeFile(file + '.br', zlib.brotliCompressSync(bytes, { params: { [zlib.constants.BROTLI_PARAM_QUALITY]: 11, [zlib.constants.BROTLI_PARAM_SIZE_HINT]: bytes.length } }));
    await fs.writeFile(file + '.gz', zlib.gzipSync(bytes, { level: 9 }));
  }
  const temporaryIndex = path.join(publicDir, 'index.html.build');
  await fs.writeFile(temporaryIndex, html);
  await fs.rename(temporaryIndex, path.join(publicDir, 'index.html'));
  for (const name of await fs.readdir(path.join(publicDir, 'assets'))) {
    const m = /^(app\.[a-f0-9]{64}\.(?:js|css))(?:\.br|\.gz)?$/.exec(name);
    if (keep && m && !keep.has(m[1])) await fs.rm(path.join(publicDir, 'assets', name), { force: true });
  }
  return { javascript: jsPath, stylesheet: cssPath, modules: [...modules.keys()] };
}

// <publicDir>/<name> as committed in the last few commits that changed it, on HEAD and on origin/main, joined;
// null when git or the history is unavailable. Several versions are kept so the release currently in
// production (usually a few commits behind) and open tabs never lose their bundle.
const COMMITTED_VERSIONS = 5;
function committedFile(publicDir, name) {
  const run = args => spawnSync('git', args, { cwd: publicDir, encoding: 'utf8' });
  const prefix = run(['rev-parse', '--show-prefix']);
  if (prefix.status !== 0) return null;
  const file = prefix.stdout.trim() + name;
  // HEAD's history plus the main branch's (what production deploys from), when that ref exists.
  const shas = new Set();
  for (const ref of ['HEAD', 'origin/main']) {
    const log = run(['log', `-n${COMMITTED_VERSIONS}`, '--format=%H', ref, '--', `:/${file}`]);
    if (log.status === 0) for (const sha of log.stdout.trim().split('\n').filter(Boolean)) shas.add(sha);
    else if (ref === 'HEAD') return null;
  }
  if (!shas.size) return null;
  const versions = [...shas].map(sha => run(['show', `${sha}:${file}`])).filter(r => r.status === 0).map(r => r.stdout);
  return versions.length ? versions.join('\n') : null;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify(await buildPublic()));
}
